// Value from GHL, or null when not provided/blank
function field(array $src, string $key): ?string {
    if (!array_key_exists($key, $src) || $src[$key] === null || is_array($src[$key])) {
        return null;
    }
    $v = trim((string) $src[$key]);
    return $v === '' ? null : $v;
}

// First non-empty value among several GHL keys
function firstField(array $src, array $keys): ?string {
    foreach ($keys as $key) {
        $v = field($src, $key);
        if ($v !== null) {
            return $v;
        }
    }
    return null;
}

// Translated label → Engage title via value_map.json; unchanged if not listed,
// '' if the map deliberately skips it (e.g. Malay language)
function translateLabel(string $name, string $value): string {
    static $map = null;
    if ($map === null) {
        $map = json_decode((string) @file_get_contents(VALUE_MAP_FILE), true) ?: [];
    }
    foreach ($map[$name] ?? [] as $label => $title) {
        if (mb_strtolower($label) === mb_strtolower($value)) {
            return $title;
        }
    }
    return $value;
}

// Match a GHL label (or raw id) against lookup_data.json; null if no match
function lookupId(array $lookups, string $name, ?string $value): ?string {
    if ($value === null) {
        return null;
    }
    $translated = translateLabel($name, $value);
    if ($translated === '') {
        logInfo("[Lookup] $name '$value' is not mapped to Engage — field skipped");
        return null;
    }
    $list   = $lookups[$name] ?? [];
    $needle = mb_strtolower($translated);
    foreach ($list as $item) {
        if (mb_strtolower($item['title']) === $needle) {
            return $item['id'];
        }
    }
    foreach ($list as $item) {
        if (mb_strtolower($item['id']) === $needle) {
            return $item['id'];
        }
    }
    logWarn("[Lookup] No $name match for '$value' — field skipped");
    return null;
}

// Engage wants ISO 8601; GHL may send Y-m-d, d/m/Y, "Nov 27th 2010", etc.
function isoDate(?string $value): ?string {
    if ($value === null) {
        return null;
    }
    $dt = DateTime::createFromFormat('!d/m/Y', $value) ?: DateTime::createFromFormat('!d-m-Y', $value);
    if (!$dt) {
        $ts = strtotime($value);
        $dt = $ts === false ? null : (new DateTime())->setTimestamp($ts);
    }
    if (!$dt) {
        logWarn("[Date] Cannot parse '$value' — field skipped");
        return null;
    }
    return $dt->format('Y-m-d\TH:i:s.000\Z');
}

function boolField(?string $value): ?bool {
    if ($value === null) {
        return null;
    }
    return filter_var($value, FILTER_VALIDATE_BOOLEAN, FILTER_NULL_ON_FAILURE);
}

// Drop keys whose value was not provided
function compact_payload(array $payload): array {
    return array_filter($payload, fn($v) => $v !== null);
}

