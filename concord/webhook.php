// GHL → Engage Admissions Middleware
// Single-file PHP webhook
//
// URL flag selects the Engage school:
//   webhook.php?env=sandbox     → Sandbox
//   webhook.php?env=production  → CL1-CCIS
//
// GHL workflow "Custom Webhook" sends the contact's standard fields plus
// these Custom Data keys (all optional; anything missing is skipped).
// Lookup fields take the text label as shown in lookup_data.json
// (case-insensitive), or the Engage ID itself.
//
//   Pupil:      student_title, student_first_name, student_middle_name,
//               student_last_name, student_gender, student_dob,
//               student_language, student_nationality
//   Admission:  date_of_entry, boarder_status, entry_year, entry_term,
//               entry_year_group, date_of_leaving, appointment_date
//   Contact:    parent_title, parent_first_name, parent_middle_name,
//               parent_last_name, parent_language,
//               relationship, is_contact_parental, priority,
//               parent_email, email_type, parent_phone, phone_type
//
// parent_first_name / parent_last_name / parent_email / parent_phone fall
// back to the GHL contact's first_name / last_name / email / phone.
//
// GHL's own "(Contact) Gender" / "(Contact) Relationship" fields (any form
// language, see GHL_*_KEYS) are read directly; translated labels are mapped
// to Engage values via value_map.json. Gender is the child's only.
// Also read the same way: Preferred Term → entryTerm, Year Group of Interest
// → entryYearGroup, Preferred Language → pupil firstLanguage (Malay → "Bahasa, Mandarin, English"),
// Programme of interest → pupil generalNotes.
// ============================================================

