header('Content-Type: application/json');

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    http_response_code(405);
    echo json_encode(['error' => 'Method not allowed']);
    exit;
}

$env      = strtolower(trim($_GET['env'] ?? ''));
$schoolId = ENGAGE_SCHOOLS[$env] ?? null;
if (!$schoolId) {
    http_response_code(400);
    echo json_encode(['error' => 'Missing or invalid ?env= flag (use sandbox or production)']);
    exit;
}

$rawBody = file_get_contents('php://input');
$payload = json_decode($rawBody, true);
if (!is_array($payload)) {
    http_response_code(400);
    echo json_encode(['error' => 'Invalid JSON']);
    exit;
}

$allLookups = json_decode((string) @file_get_contents(LOOKUP_FILE), true);
$lookups    = $allLookups[$env] ?? null;
if (!$lookups) {
    http_response_code(500);
    echo json_encode(['error' => "No lookup data for $env — run getLookup.py"]);
    exit;
}

logInfo("========== WEBHOOK RECEIVED ($env → $schoolId) ==========");
logInfo('Raw payload: ' . $rawBody);

// GHL may nest under raw_body; custom data keys override contact fields
$body = $payload['raw_body'] ?? $payload;
$d    = array_merge($body, is_array($body['customData'] ?? null) ? $body['customData'] : []);

// GHL Gender is the child's; the parent contact is always "Not known" (U)
$ghlGender       = firstField($d, GHL_GENDER_KEYS);
$ghlRelationship = firstField($d, GHL_RELATIONSHIP_KEYS);
$ghlTerm         = firstField($d, GHL_TERM_KEYS);
$ghlYearGroup    = firstField($d, GHL_YEAR_GROUP_KEYS);
$ghlProgramme    = firstField($d, GHL_PROGRAMME_KEYS);
$ghlLanguage     = firstField($d, GHL_LANGUAGE_KEYS);
// GHL's DOB field name uses a curly apostrophe (Child’s)
$ghlDob          = firstField($d, ["(Contact) Child’s Date of Birth", "(Contact) Child's Date of Birth"]);
$ghlNationality  = field($d, "(Contact) Child's Nationality");
$ghlTitle        = field($d, '(Contact) Title');
// One-field child name is never split: whole name as surname, forename "-"
$ghlChildName    = field($d, "(Contact) Child's Name");
$ghlEmailType    = firstField($d, ['(Contact) Email Type', 'Email Type']);
$ghlPhoneType    = firstField($d, ['(Contact) Telephone Number Type', 'Telephone Type']);

// Respond to GHL immediately (so it doesn't timeout)
http_response_code(200);
echo json_encode(['status' => 'received', 'env' => $env, 'contactId' => $body['contact_id'] ?? null]);
if (function_exists('fastcgi_finish_request')) {
    fastcgi_finish_request();
} else {
    header('Connection: close');
    while (ob_get_level() > 0) {
        ob_end_flush();
    }
    flush();
}
ignore_user_abort(true);
set_time_limit(300);

