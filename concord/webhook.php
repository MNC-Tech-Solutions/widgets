// BACKGROUND PROCESSING (after response sent)
// ============================================================
logInfo('===== START PROCESSING =====');

// Step 1: Engage token
$token = getEngageToken();
if (!$token) {
    logError('Cannot proceed without Engage token');
    exit;
}

// Step 2: Add pupil
$pupil = compact_payload([
    'titleId'       => lookupId($lookups, 'title', field($d, 'student_title')),
    'forename'      => field($d, 'student_first_name') ?? ($ghlChildName !== null ? '-' : null),
    'middleName'    => field($d, 'student_middle_name'),
    'surname'       => field($d, 'student_last_name') ?? ($ghlChildName !== null ? mb_substr($ghlChildName, 0, 50) : null),
    // Engage requires gender: fall back to "Not known", as for contacts
    'genderId'      => lookupId($lookups, 'gender', field($d, 'student_gender') ?? $ghlGender) ?? 'U',
    'dob'           => isoDate(field($d, 'student_dob') ?? $ghlDob),
    'firstLanguage' => lookupId($lookups, 'language', field($d, 'student_language') ?? $ghlLanguage),
]);
$isDummyPupil = false;
if (!isset($pupil['forename']) && !isset($pupil['surname'])) {
    logInfo('No pupil name provided — using dummy pupil');
    $isDummyPupil = true;
    $pupil = ['forename' => 'Dummy', 'surname' => 'Student', 'genderId' => 'F'];
}
// Engage has no programme field — kept in the pupil's general notes, in English
if ($ghlProgramme !== null) {
    $pupil['generalNotes'] = 'Programme of interest: ' . translateLabel('programme', $ghlProgramme);
}

$result  = engagePost($token, "AddPrPupilBasic/$schoolId", $pupil, 'addPupil');
$pupilId = $result['ok'] ? extractId($result['body'], ['newPupilId', 'pupilId', 'id']) : null;
if (!$pupilId) {
    logError('Pupil not created — stopping');
    exit;
}
logOk("Pupil created: $pupilId");

// Step 3: Nationality
$nationalityId = lookupId($lookups, 'nationality', field($d, 'student_nationality') ?? $ghlNationality);
if ($nationalityId) {
    engagePost($token, "AddNationlityInfo/$schoolId/$pupilId", ['nationalityId' => $nationalityId], 'addNationality');
}

// Step 4: Admission details
$admission = compact_payload([
    'dateOfEntry'     => isoDate(field($d, 'date_of_entry')),
    'boarderStatusId' => lookupId($lookups, 'boarder_status', field($d, 'boarder_status')),
    'entryYear'       => field($d, 'entry_year'),
    'entryTerm'       => lookupId($lookups, 'entry_term', field($d, 'entry_term') ?? $ghlTerm),
    'entryYearGroup'  => lookupId($lookups, 'year_group', field($d, 'entry_year_group') ?? $ghlYearGroup),
    'dateOfLeaving'   => isoDate(field($d, 'date_of_leaving')),
    'appointmentDate' => isoDate(field($d, 'appointment_date')),
]);
// Always sent so the pupil gets an admission stage
$path = "AddAdmissionDetails/$schoolId/$pupilId";
if ($isDummyPupil) {
    $admission['currentAdmissionStageId'] = DUMMY_PUPIL_STAGE_ID;
} else {
    $path .= '?usedefaultstage=true';
}
engagePost($token, $path, $admission, 'addAdmission');

// Step 5: Parent contact
$parent = [
    'firstName' => field($d, 'parent_first_name') ?? field($d, 'first_name'),
    'lastName'  => field($d, 'parent_last_name')  ?? field($d, 'last_name'),
    'email'     => field($d, 'parent_email')      ?? field($d, 'email'),
    'phone'     => field($d, 'parent_phone')      ?? field($d, 'phone'),
];
if (!array_filter($parent)) {
    logWarn('No parent contact details provided — done');
    exit;
}
// Engage requires both names; like the child, a one-part name goes in as surname with forename "-"
if ($parent['lastName'] === null) {
    $parent['lastName']  = $parent['firstName'] ?? '-';
    $parent['firstName'] = '-';
} elseif ($parent['firstName'] === null) {
    $parent['firstName'] = '-';
}

$link = compact_payload([
    'relationshipId'    => lookupId($lookups, 'relationship', field($d, 'relationship') ?? $ghlRelationship) ?? DEFAULT_RELATIONSHIP_ID,
    'isContactParental' => boolField(field($d, 'is_contact_parental')) ?? true,
    'priority'          => (int) (field($d, 'priority') ?? 1),
]);

$result  = engagePost($token, "IsContactExisting/$schoolId", compact_payload([
    'firstName'    => $parent['firstName'],
    'lastName'     => $parent['lastName'],
    'telephone'    => $parent['phone'],
    'emailAddress' => $parent['email'],
]), 'isContactExisting');
$matches = $result['ok'] ? json_decode($result['body'], true) : null;
$match   = is_array($matches) ? ($matches[0] ?? ($matches ? $matches : null)) : null;
$contactId = is_array($match) ? extractId(json_encode($match), ['contactId', 'id']) : null;

if ($contactId) {
    // 5.2 Link existing contact (it already has its own email/phone in Engage)
    logInfo("Existing contact found: $contactId");
    engagePost($token, "LinkExistingContact/$schoolId/$pupilId/$contactId", $link, 'linkContact');
    logInfo('===== DONE =====');
    exit;
}

// 5.1 New contact
$fullName = trim(implode(' ', array_filter(
    [$parent['firstName'], field($d, 'parent_middle_name'), $parent['lastName']],
    fn($part) => $part !== null && $part !== '-'
)));
$contact  = compact_payload($link + [
    // Engage requires title and gender: title "Others" (blank if the school has none), gender "Not known"
    'titleId'     => lookupId($lookups, 'title', field($d, 'parent_title') ?? $ghlTitle ?? 'Others') ?? '00',
    'firstName'   => $parent['firstName'],
    'middleName'  => field($d, 'parent_middle_name'),
    'lastName'    => $parent['lastName'],
    'contactName' => $fullName !== '' ? $fullName : null,
    'genderId'    => 'U',
    'languageId'  => lookupId($lookups, 'language', field($d, 'parent_language')),
]);
$result    = engagePost($token, "AddContactBasicInfo/$schoolId/$pupilId", $contact, 'addContact');
$contactId = $result['ok'] ? extractId($result['body'], ['newContactId', 'contactId', 'id']) : null;
if (!$contactId) {
    logError('Contact not created — skipping email/telephone');
    exit;
}
logOk("Contact created: $contactId");

// Step 6: Email
