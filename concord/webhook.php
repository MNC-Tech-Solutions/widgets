// HTTP HELPER with RETRY
// ============================================================
function httpRequest(string $method, string $url, array $headers = [], $body = null, string $label = 'request'): array {
    $delays = [1, 3, 7];
    $lastCode = 0;
    $lastBody = '';

    for ($attempt = 1; $attempt <= 3; $attempt++) {
        $ch = curl_init();
        curl_setopt($ch, CURLOPT_URL, $url);
        curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
        curl_setopt($ch, CURLOPT_TIMEOUT, 30);
        curl_setopt($ch, CURLOPT_FOLLOWLOCATION, true);
        curl_setopt($ch, CURLOPT_ENCODING, '');

        // Engage returns 403 without a browser/Postman-like User-Agent
        $headerLines = [
            'User-Agent: PostmanRuntime/7.32.3',
            'Accept: */*',
            'Connection: keep-alive',
        ];
        foreach ($headers as $k => $v) {
            $headerLines[] = "$k: $v";
        }
        curl_setopt($ch, CURLOPT_HTTPHEADER, $headerLines);

        // Optional: Bypass SSL issues if your server's certs are old
        curl_setopt($ch, CURLOPT_SSL_VERIFYPEER, false);

        if ($method === 'POST') {
            curl_setopt($ch, CURLOPT_POST, true);
            if ($body !== null) {
                curl_setopt($ch, CURLOPT_POSTFIELDS, $body);
            }
        }

        $response   = curl_exec($ch);
        $httpCode   = curl_getinfo($ch, CURLINFO_HTTP_CODE);
        $curlError  = curl_error($ch);
        curl_close($ch);

        if ($curlError) {
            logWarn("[$label] Attempt $attempt/3 curl error: $curlError");
        } elseif ($httpCode >= 200 && $httpCode < 300) {
            return ['ok' => true, 'code' => $httpCode, 'body' => $response];
        } else {
            logWarn("[$label] Attempt $attempt/3 HTTP $httpCode: $response");
            $lastCode = $httpCode;
            $lastBody = (string) $response;
            // 4xx = bad request data; retrying won't help (except 401/429)
            if ($httpCode >= 400 && $httpCode < 500 && !in_array($httpCode, [401, 408, 429], true)) {
                break;
            }
        }

        if ($attempt < 3) {
            $wait = $delays[$attempt - 1];
            logInfo("[$label] Retrying in {$wait}s...");
            sleep($wait);
        }
    }

    logError("[$label] Request failed");
    return ['ok' => false, 'code' => $lastCode, 'body' => $lastBody];
}

// ============================================================
// ENGAGE AUTH - token cached in file
// ============================================================
function getEngageToken(): ?string {
    if (file_exists(TOKEN_CACHE_FILE)) {
        $cache = json_decode(file_get_contents(TOKEN_CACHE_FILE), true);
        if ($cache && isset($cache['access_token'], $cache['expires_at']) && time() < $cache['expires_at']) {
            logInfo('[Engage] Using cached token');
            return $cache['access_token'];
        }
    }

    if (ENGAGE_USERNAME === '' || ENGAGE_PASSWORD === '') {
        logError('[Engage] ENGAGE_USERNAME / ENGAGE_PASSWORD not set — add them to concord/.env');
        return null;
    }

    logInfo('[Engage] Fetching new token...');
    $body = http_build_query([
        'username' => ENGAGE_USERNAME,
        'password' => ENGAGE_PASSWORD,
    ]);

    $result = httpRequest('POST', ENGAGE_BASE_URL . '/api/gettoken', [
        'Content-Type' => 'application/x-www-form-urlencoded',
    ], $body, 'getToken');

    if (!$result['ok']) {
        logError('[Engage] Failed to get token');
        return null;
    }

    $data  = json_decode($result['body'], true);
    $token = $data['access_token'] ?? null;

    if (!$token) {
        logError('[Engage] Token missing from response: ' . $result['body']);
        return null;
    }

    // Cache until 10 minutes before expiry
    $expiresIn = (int) ($data['expires_in'] ?? 3600);
    file_put_contents(TOKEN_CACHE_FILE, json_encode([
        'access_token' => $token,
        'expires_at'   => time() + max(60, $expiresIn - 600),
    ]));

    logOk('[Engage] Token obtained and cached');
    return $token;
}

// ============================================================
// ENGAGE - POST helper
// ============================================================
function engagePost(string $token, string $path, array $payload, string $label): array {
    $json = json_encode($payload, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    logInfo("[$label] POST $path $json");

    $result = httpRequest('POST', ENGAGE_BASE_URL . '/api/v1/admissions/' . $path, [
        'Authorization' => 'Bearer ' . $token,
        'Content-Type'  => 'application/json',
    ], $json, $label);

    logInfo("[$label] Response: " . $result['body']);

    // Engage reports some failures as HTTP 200 with e.g. {"addStatus":"Missing Default/Current Stage"}
    $status = json_decode($result['body'], true)['addStatus'] ?? null;
    if (is_string($status) && preg_match('/missing|fail|error|invalid|not /i', $status)) {
        logWarn("[$label] Engage rejected: $status");
        $result['ok'] = false;
    }
    return $result;
}

// Engage returns new ids either as a bare value or inside an object
function extractId(string $body, array $keys): ?string {
    $data = json_decode($body, true);
    if (is_scalar($data) && (string) $data !== '') {
        return (string) $data;
    }
    if (is_array($data)) {
        $lower = array_change_key_case($data, CASE_LOWER);
        foreach ($keys as $k) {
            $v = $lower[strtolower($k)] ?? null;
            if (is_scalar($v) && (string) $v !== '') {
                return (string) $v;
            }
        }
        if (isset($data['data']) && is_array($data['data'])) {
            return extractId(json_encode($data['data']), $keys);
        }
    }
    $trimmed = trim($body, " \t\n\r\"");
    return ($trimmed !== '' && strpbrk($trimmed, '{}[] ') === false) ? $trimmed : null;
}

