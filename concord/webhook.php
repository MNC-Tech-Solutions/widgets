        'emailTypeId'  => lookupId($lookups, 'email_type', field($d, 'email_type') ?? $ghlEmailType) ?? DEFAULT_CONTACT_TYPES[$env]['email'],
        'email'        => $parent['email'],
        'primaryEmail' => true,
    ]), 'addEmail');
